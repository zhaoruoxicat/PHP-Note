CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 username VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 session_version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS note_groups (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL,
 group_type ENUM('normal','anonymous') NOT NULL DEFAULT 'normal',
 system_slot TINYINT GENERATED ALWAYS AS (IF(group_type = 'anonymous', 1, NULL)) STORED,
 UNIQUE KEY unique_inbox (system_slot),
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS note_messages (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 group_id BIGINT UNSIGNED NOT NULL,
 content MEDIUMTEXT NOT NULL,
 source_type ENUM('admin','anonymous') NOT NULL DEFAULT 'admin',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 KEY group_time (group_id, created_at, id),
 FOREIGN KEY (group_id) REFERENCES note_groups(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS note_attachments (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 message_id BIGINT UNSIGNED NOT NULL,
 original_name VARCHAR(255) NOT NULL,
 storage_name VARCHAR(100) NOT NULL UNIQUE,
 mime_type VARCHAR(150) NOT NULL,
 file_size BIGINT UNSIGNED NOT NULL,
 file_extension VARCHAR(10) NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 KEY message_files (message_id),
 FOREIGN KEY (message_id) REFERENCES note_messages(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS auth_sessions (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT UNSIGNED NOT NULL,
 session_key_hash CHAR(64) NOT NULL UNIQUE,
 session_version INT UNSIGNED NOT NULL,
 device_name VARCHAR(150) NOT NULL,
 last_ip VARCHAR(45) NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 last_seen_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 expires_at DATETIME(6) NOT NULL,
 revoked_at DATETIME(6) NULL,
 KEY active_sessions (user_id, revoked_at, expires_at),
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS anonymous_tokens (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 code_hmac CHAR(64) NOT NULL UNIQUE,
 code_hint CHAR(2) NOT NULL,
 duration_minutes SMALLINT UNSIGNED NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 expires_at DATETIME(6) NOT NULL,
 revoked_at DATETIME(6) NULL,
 submit_count INT UNSIGNED NOT NULL DEFAULT 0,
 uploaded_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS sync_state (
 id TINYINT UNSIGNED PRIMARY KEY,
 current_seq BIGINT UNSIGNED NOT NULL DEFAULT 0,
 min_cursor BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT IGNORE INTO sync_state (id) VALUES (1);

CREATE TABLE IF NOT EXISTS sync_events (
 seq BIGINT UNSIGNED PRIMARY KEY,
 event_type VARCHAR(40) NOT NULL,
 group_id BIGINT UNSIGNED NULL,
 message_id BIGINT UNSIGNED NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 KEY event_age (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS rate_limits (
 rate_key CHAR(64) PRIMARY KEY,
 hits INT UNSIGNED NOT NULL DEFAULT 0,
 expires_at DATETIME(6) NOT NULL,
 KEY expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS file_garbage (
 storage_name VARCHAR(100) PRIMARY KEY,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS nextcloud_note_meta (
 message_id BIGINT UNSIGNED PRIMARY KEY,
 title VARCHAR(255) NOT NULL,
 favorite BOOLEAN NOT NULL DEFAULT FALSE,
 modified BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY (message_id) REFERENCES note_messages(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS nextcloud_login_flows (
 poll_hash CHAR(64) PRIMARY KEY,
 grant_hash CHAR(64) NOT NULL UNIQUE,
 device_name VARCHAR(120) NOT NULL,
 session_id BIGINT UNSIGNED NULL,
 sealed_password TEXT NULL,
 expires_at DATETIME(6) NOT NULL,
 KEY flow_expiry (expires_at),
 FOREIGN KEY (session_id) REFERENCES auth_sessions(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS browser_devices (
 user_id BIGINT UNSIGNED NOT NULL,
 device_hash CHAR(64) NOT NULL,
 session_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY (user_id, device_hash),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (session_id) REFERENCES auth_sessions(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS login_audit (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT UNSIGNED NOT NULL,
 session_id BIGINT UNSIGNED NULL,
 login_ip VARCHAR(45) NOT NULL,
 location_json JSON NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 KEY user_logins (user_id, created_at),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (session_id) REFERENCES auth_sessions(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ip_geo_cache (
 ip VARCHAR(45) PRIMARY KEY,
 location_json JSON NOT NULL,
 expires_at DATETIME(6) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
